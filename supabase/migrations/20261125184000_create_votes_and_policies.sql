create table public.votes (
  id bigint generated by default as identity primary key,
  rating text not null check (rating in ('만족', '보통', '불만족')),
  created_at timestamptz not null default now()
);

alter table public.votes enable row level security;

revoke all on table public.votes from public, anon, authenticated;
grant usage on schema public to anon, authenticated;
grant insert (rating) on table public.votes to anon, authenticated;
grant select, delete on table public.votes to authenticated;

create policy "Anyone can submit a vote"
  on public.votes for insert
  to anon
  with check (true);

create policy "Admins can view votes"
  on public.votes for select
  to authenticated
  using (true);

create policy "Admins can submit votes"
  on public.votes for insert
  to authenticated
  with check (true);

create policy "Admins can delete votes"
  on public.votes for delete
  to authenticated
  using (true);
